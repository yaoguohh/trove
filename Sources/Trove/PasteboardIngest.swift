import AppKit
import ImageIO
import UniformTypeIdentifiers

/// Pure decision layer for one pasteboard change: whether to ingest it at all, and whether the
/// content is the text or the image. Kept free of NSPasteboard so the precedence and hygiene rules
/// are unit-testable; `ClipboardMonitor.poll` reads the pasteboard and applies the decision.
enum PasteboardIngest {
    enum ImageType: Equatable, Sendable {
        case png
        case tiff

        var pasteboardType: NSPasteboard.PasteboardType {
            switch self {
            case .png: .png
            case .tiff: .tiff
            }
        }
    }

    enum Decision: Equatable {
        /// Skip this change entirely (transient / concealed / password-manager payloads).
        case ignore(IgnoreReason)
        /// Nothing we store (no string, no bitmap — e.g. a file-only or custom-type copy).
        case nothing
        case text(String)
        /// Store the bitmap; read it as this type (PNG preferred: stored verbatim, no re-encode).
        case image(ImageType)
    }

    enum IgnoreReason: Equatable {
        case transient
        case concealed
    }

    /// nspasteboard.org conventions plus the private markers text expanders stamp on their
    /// auto-generated writes. Same default set as Maccy (`Defaults.Keys+Names.swift`).
    static let transientTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",   // Keyboard Maestro & co.
        "com.typeit4me.clipping",
        "Pasteboard generator type"                  // Typinator
    ]

    /// Password managers mark secrets as concealed; they must never reach history.json.
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb"
    ]

    /// `types` are the pasteboard's declared type identifiers; `string` is its plain-text
    /// representation (nil when absent).
    static func decide(types: [String], string: String?) -> Decision {
        if types.contains(where: concealedTypes.contains) { return .ignore(.concealed) }
        if types.contains(where: transientTypes.contains) { return .ignore(.transient) }

        let imageType: ImageType? = types.contains(ImageType.png.pasteboardType.rawValue) ? .png
            : types.contains(ImageType.tiff.pasteboardType.rawValue) ? .tiff
            : nil
        let text = string.flatMap { $0.isEmpty ? nil : $0 }

        // Text first (CopyQ's rule): a rich copy from Pages, Numbers, Keynote or Preview carries a
        // PDF/TIFF rendering of the selection alongside the string, and the string is the content.
        // The image wins only when there is no text, or when the text is just the image's address
        // (Safari's Copy Image puts the URL on the pasteboard next to the bitmap).
        if let text, imageType == nil || !isIncidentalText(text) {
            return .text(text)
        }
        if let imageType {
            return .image(imageType)
        }
        return .nothing
    }

    /// Text that merely names the bitmap next to it rather than being the copied content.
    static func isIncidentalText(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, !trimmed.contains(where: { $0 == "\n" || $0 == " " }) else { return false }
        return RichPreviewRenderer.isSingleURL(trimmed) || trimmed.hasPrefix("file://")
    }
}

/// A bitmap lifted off the pasteboard: the raw bytes plus which type they were read as.
struct PasteboardImagePayload: Sendable, Equatable {
    let data: Data
    let type: PasteboardIngest.ImageType
}

/// Image normalisation and thumbnailing for storage. ImageIO only — thread-safe, no AppKit — so
/// every function here can run on a background task; the monitor never encodes on the main thread.
enum ImageIngest {
    /// Ceiling on a single pasteboard bitmap we are willing to store (CopyQ caps per-MIME reads too).
    static let maxImageBytes = 64 * 1024 * 1024
    /// Card thumbnails are rendered at ≤ ~300×140pt (600×280px); 640px covers that with headroom.
    static let thumbnailMaxPixelSize = 640

    enum ThumbnailResult: Equatable {
        /// A downsampled PNG was produced.
        case generated(Data)
        /// The original is already within `thumbnailMaxPixelSize`; use it as its own thumbnail.
        case notNeeded
        /// The data could not be decoded.
        case failed
    }

    struct StoredFiles: Sendable, Equatable {
        let imageFileName: String
        let thumbnailFileName: String?
    }

    static func imageFileName(for id: UUID) -> String { "\(id.uuidString).png" }
    static func thumbnailFileName(for id: UUID) -> String { "\(id.uuidString).thumb.png" }

    /// PNG passes through verbatim (what the source app produced — no decode, no re-encode).
    /// Anything else is decoded once and encoded to PNG.
    static func pngData(from payload: PasteboardImagePayload) -> Data? {
        if payload.type == .png { return payload.data }
        guard let source = CGImageSourceCreateWithData(payload.data as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        return encodePNG(image)
    }

    /// A PNG no larger than `maxPixelSize` on its long edge, produced by ImageIO's downsampling
    /// decoder (never materialises the full bitmap when the source is much larger).
    static func thumbnail(from png: Data, maxPixelSize: Int = thumbnailMaxPixelSize) -> ThumbnailResult {
        guard let source = CGImageSourceCreateWithData(png as CFData, nil) else { return .failed }
        if let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
           let width = properties[kCGImagePropertyPixelWidth] as? Int,
           let height = properties[kCGImagePropertyPixelHeight] as? Int,
           max(width, height) <= maxPixelSize {
            return .notNeeded
        }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelSize,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceShouldCacheImmediately: true
        ]
        guard let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary),
              let data = encodePNG(thumbnail) else { return .failed }
        return .generated(data)
    }

    /// Writes the image (and its thumbnail, when one is needed) atomically into `directory`.
    static func writeFiles(id: UUID, png: Data, directory: URL) throws -> StoredFiles {
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let imageName = imageFileName(for: id)
        try png.write(to: directory.appendingPathComponent(imageName), options: .atomic)

        let thumbnailName: String?
        switch thumbnail(from: png) {
        case .generated(let data):
            let name = thumbnailFileName(for: id)
            try data.write(to: directory.appendingPathComponent(name), options: .atomic)
            thumbnailName = name
        case .notNeeded:
            thumbnailName = imageName
        case .failed:
            thumbnailName = nil
        }
        return StoredFiles(imageFileName: imageName, thumbnailFileName: thumbnailName)
    }

    private static func encodePNG(_ image: CGImage) -> Data? {
        let data = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(data as CFMutableData, UTType.png.identifier as CFString, 1, nil) else {
            return nil
        }
        CGImageDestinationAddImage(destination, image, nil)
        guard CGImageDestinationFinalize(destination) else { return nil }
        return data as Data
    }
}

/// Owns the pasteboard after Trove writes an image. The stored PNG bytes go on eagerly (verbatim —
/// what we ingested); the TIFF rendition that a few older consumers insist on is produced only if
/// one actually asks, so a paste never pays for an encode nobody reads.
final class ImagePasteboardOwner: NSObject, NSPasteboardTypeOwner, @unchecked Sendable {
    private let png: Data

    init(png: Data) {
        self.png = png
    }

    func pasteboard(_ sender: NSPasteboard, provideDataForType type: NSPasteboard.PasteboardType) {
        switch type {
        case .png:
            sender.setData(png, forType: .png)
        case .tiff:
            if let tiff = NSImage(data: png)?.tiffRepresentation {
                sender.setData(tiff, forType: .tiff)
            }
        default:
            break
        }
    }
}

import AppKit

/// Pure decision layer for one pasteboard change: whether to ingest it at all, and whether the
/// content is the text or the image. Kept free of NSPasteboard so the precedence and hygiene rules
/// are unit-testable; `ClipboardMonitor.poll` reads the pasteboard and applies the decision.
enum PasteboardIngest {
    enum ImageType: Equatable, Sendable {
        case png
        case tiff

        var pasteboardType: NSPasteboard.PasteboardType {
            switch self {
            case .png: .png
            case .tiff: .tiff
            }
        }
    }

    enum Decision: Equatable {
        /// Skip this change entirely (transient / concealed / password-manager payloads).
        case ignore(IgnoreReason)
        /// Nothing we store (no string, no bitmap — e.g. a file-only or custom-type copy).
        case nothing
        case text(String)
        /// Store the bitmap; read it as this type (PNG preferred: stored verbatim, no re-encode).
        case image(ImageType)
    }

    enum IgnoreReason: Equatable {
        case transient
        case concealed
    }

    /// nspasteboard.org conventions plus the private markers text expanders stamp on their
    /// auto-generated writes. Same default set as Maccy (`Defaults.Keys+Names.swift`).
    static let transientTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",   // Keyboard Maestro & co.
        "com.typeit4me.clipping",
        "Pasteboard generator type"                  // Typinator
    ]

    /// Password managers mark secrets as concealed; they must never reach history.json.
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "net.antelle.keeweb"
    ]

    /// `types` are the pasteboard's declared type identifiers; `string` is its plain-text
    /// representation (nil when absent).
    static func decide(types: [String], string: String?) -> Decision {
        if types.contains(where: concealedTypes.contains) { return .ignore(.concealed) }
        if types.contains(where: transientTypes.contains) { return .ignore(.transient) }

        let imageType: ImageType? = types.contains(ImageType.png.pasteboardType.rawValue) ? .png
            : types.contains(ImageType.tiff.pasteboardType.rawValue) ? .tiff
            : nil
        let text = string.flatMap { $0.isEmpty ? nil : $0 }

        // Text first (CopyQ's rule): a rich copy from Pages, Numbers, Keynote or Preview carries a
        // PDF/TIFF rendering of the selection alongside the string, and the string is the content.
        // The image wins only when there is no text, or when the text is just the image's address
        // (Safari's Copy Image puts the URL on the pasteboard next to the bitmap).
        if let text, imageType == nil || !isIncidentalText(text) {
            return .text(text)
        }
        if let imageType {
            return .image(imageType)
        }
        return .nothing
    }

    /// Text that merely names the bitmap next to it rather than being the copied content.
    static func isIncidentalText(_ text: String) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, !trimmed.contains(where: { $0 == "\n" || $0 == " " }) else { return false }
        return Clip.isSingleURL(trimmed) || trimmed.hasPrefix("file://")
    }
}

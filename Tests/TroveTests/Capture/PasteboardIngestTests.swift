import Foundation
import AppKit
import Testing
@testable import Trove

/// The pure precedence + hygiene rules `ClipboardMonitor.poll` applies to each pasteboard change.
struct PasteboardIngestDecisionTests {
    private let text = "public.utf8-plain-text"

    @Test func concealedPayloadsAreIgnored() {
        #expect(PasteboardIngest.decide(types: [text, "org.nspasteboard.ConcealedType"], string: "hunter2") == .ignore(.concealed))
        #expect(PasteboardIngest.decide(types: ["com.agilebits.onepassword", text], string: "pw") == .ignore(.concealed))
        #expect(PasteboardIngest.decide(types: ["net.antelle.keeweb", text], string: "pw") == .ignore(.concealed))
    }

    @Test func transientPayloadsAreIgnored() {
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                       "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type"] {
            #expect(PasteboardIngest.decide(types: [text, marker], string: "expanded") == .ignore(.transient), "\(marker)")
        }
    }

    @Test func concealedOutranksTransient() {
        #expect(PasteboardIngest.decide(types: ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType"], string: "x") == .ignore(.concealed))
    }

    @Test func textWinsOverARichRendering() {
        // Pages / Numbers / Preview put a PDF or TIFF rendering of the selection next to the string.
        let types = [text, "com.adobe.pdf", "public.tiff", "public.rtf"]
        #expect(PasteboardIngest.decide(types: types, string: "Quarterly totals") == .text("Quarterly totals"))
    }

    @Test func imageWinsWhenThereIsNoText() {
        #expect(PasteboardIngest.decide(types: ["public.png", "public.tiff"], string: nil) == .image(.png))
        #expect(PasteboardIngest.decide(types: ["public.tiff"], string: nil) == .image(.tiff))
        #expect(PasteboardIngest.decide(types: ["public.tiff", text], string: "") == .image(.tiff))
    }

    @Test func pngIsPreferredOverTIFF() {
        #expect(PasteboardIngest.decide(types: ["public.tiff", "public.png"], string: nil) == .image(.png))
    }

    @Test func imageWinsWhenTheTextIsJustItsAddress() {
        // Safari's Copy Image: the bitmap plus the image URL as plain text.
        #expect(PasteboardIngest.decide(types: ["public.tiff", text], string: "https://example.com/pic.png") == .image(.tiff))
        #expect(PasteboardIngest.decide(types: ["public.png", text], string: "file:///Users/me/pic.png") == .image(.png))
    }

    @Test func realTextNextToAnImageStaysText() {
        #expect(PasteboardIngest.decide(types: ["public.png", text], string: "see https://example.com for details") == .text("see https://example.com for details"))
        #expect(PasteboardIngest.decide(types: ["public.png", text], string: "line one\nline two") == .text("line one\nline two"))
    }

    @Test func aURLWithoutAnImageIsOrdinaryText() {
        #expect(PasteboardIngest.decide(types: [text], string: "https://example.com/pic.png") == .text("https://example.com/pic.png"))
    }

    @Test func nothingStorableYieldsNothing() {
        #expect(PasteboardIngest.decide(types: [text], string: "") == .nothing)
        #expect(PasteboardIngest.decide(types: ["public.file-url"], string: nil) == .nothing)
        #expect(PasteboardIngest.decide(types: [], string: nil) == .nothing)
    }
}
